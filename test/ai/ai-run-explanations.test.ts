describe('NFR-06: the call budget guard', () => {
  it('allows exactly three calls and refuses the fourth', async () => {
    const run = new AiRun('proj');
    const noop = async () => ({});
    await run.track('analysis', 'm', undefined, noop);
    await run.track('embedding', 'm', undefined, noop);
    await run.track('explanation', 'm', undefined, noop);

    expect(run.callCount).toBe(3);
    expect(run.remaining).toBe(0);
    await expect(run.track('embedding', 'm', undefined, noop)).rejects.toBeInstanceOf(
      CallBudgetExceededError
    );
  });

  it('counts a failed call against the budget, because it still left the machine', async () => {
    const run = new AiRun('proj');
    await expect(
      run.track('analysis', 'm', undefined, async () => {
        throw new Error('rate limited');
      })
    ).rejects.toThrow('rate limited');

    expect(run.callCount).toBe(1);
    expect(run.remaining).toBe(2);
  });

  it('records real token usage from the SDK metadata', async () => {
    const run = new AiRun('proj');
    await run.track('analysis', 'm', readUsage, async () => ({
      usageMetadata: { promptTokenCount: 10, candidatesTokenCount: 5 },
    }));
    const summary = run.finish('success');

    expect(summary?.promptTokens).toBe(10);
    expect(summary?.completionTokens).toBe(5);
  });

  it('leaves tokens null when the provider reports none, never inventing a number', async () => {
    const run = new AiRun('proj');
    await run.track('analysis', 'm', readUsage, async () => ({}));
    const summary = run.finish('success');

    expect(summary?.promptTokens).toBeNull();
    expect(summary?.completionTokens).toBeNull();
  });

  it('sums tokens across calls', async () => {
    const run = new AiRun('proj');
    const usage = (v: unknown) => (v as { usageMetadata?: { promptTokenCount?: number } }).usageMetadata;
    await run.track('analysis', 'm', usage, async () => ({ usageMetadata: { promptTokenCount: 100 } }));
    await run.track('embedding', 'm', usage, async () => ({ usageMetadata: { promptTokenCount: 30 } }));
    const summary = run.finish('success');

    expect(summary?.promptTokens).toBe(130);
  });

  it('measures duration', async () => {
    const run = new AiRun('proj');
    await run.track('analysis', 'm', undefined, async () => {
      await new Promise((r) => setTimeout(r, 15));
      return {};
    });
    const summary = run.finish('success');

    expect(summary!.durationMs).toBeGreaterThanOrEqual(10);
    expect(summary!.calls[0].durationMs).toBeGreaterThanOrEqual(10);
  });

  it('finish is idempotent so a written row cannot mutate later', () => {
    const run = new AiRun('proj');
    expect(run.finish('success')).not.toBeNull();
    expect(run.finish('error')).toBeNull();
  });
});

describe('NFR-43/44/45: AiRun recording', () => {
  const summary = (over: Partial<Parameters<AiRun['finish']> extends never ? never : object> = {}) => ({
    projectId: '11111111-1111-1111-1111-111111111111',
    callCount: 2,
    promptTokens: 150,
    completionTokens: 60,
    model: 'gemini-2.5-flash',
    status: 'success' as const,
    durationMs: 900,
    errorMessage: null,
    calls: [],
    ...over,
  });

  it('writes one row for a successful run', async () => {
    const out = await recordAiRun(summary());

    expect(out.written).toBe(true);
    expect(db.inserted).toHaveLength(1);
    expect(db.inserted[0]).toMatchObject({
      project_id: '11111111-1111-1111-1111-111111111111',
      prompt_tokens: 150,
      completion_tokens: 60,
      model: 'gemini-2.5-flash',
      status: 'success',
    });
  });

  it('writes a fallback run with fallback status', async () => {
    await recordAiRun(summary({ status: 'fallback', callCount: 1 }));

    expect(db.inserted[0].status).toBe('fallback');
  });

  it('writes an error run', async () => {
    const out = await recordAiRun(summary({ status: 'error', callCount: 0, errorMessage: 'boom' }));

    expect(out.written).toBe(true);
    expect(db.inserted[0].status).toBe('error');
  });

  it('keeps null tokens null instead of zero-filling', async () => {
    await recordAiRun(summary({ promptTokens: null, completionTokens: null }));

    expect(db.inserted[0].prompt_tokens).toBeNull();
    expect(db.inserted[0].completion_tokens).toBeNull();
  });

  it('uses a non-null model when a run made no calls', async () => {
    // `model` is NOT NULL; a fully cached run has no model of its own.
    await recordAiRun(summary({ callCount: 0, model: '' }));

    expect(db.inserted[0].model).toBe('none');
  });

  it('reports a rejected insert without throwing', async () => {
    db.failInsert = true;
    const out = await recordAiRun(summary());

    expect(out.written).toBe(false);
  });

  it('reports a thrown insert without throwing', async () => {
    db.throwInsert = true;
    const out = await recordAiRun(summary());

    expect(out.written).toBe(false);
  });

  it('refuses to persist a run above the PRD budget', async () => {
    await expect(recordAiRun(summary({ callCount: MAX_GEMINI_CALLS_PER_PROCESS + 1 }))).rejects.toThrow(
      /above the PRD budget/
    );
    expect(db.inserted).toHaveLength(0);
  });

  it('exposes count and duration that the schema cannot hold', async () => {
    const out = await recordAiRun(summary({ callCount: 3, durationMs: 1234 }));

    // Documented schema gap: measured, returned, not persisted.
    expect(out.gap.callCount).toBe(3);
    expect(out.gap.durationMs).toBe(1234);
    expect(Object.keys(db.inserted[0])).not.toContain('call_count');
  });
});

describe('FR-09: AI explanations', () => {
  const ctx = (): ExplanationContext => ({
    memberNames: { m1: 'Budi', m2: 'Sari' },
    candidatesByTask: { t1: ['m1', 'm2'], t2: ['m1', 'm2'] },
    targets: [
      { task: tasks[0], member: members[0], breakdown: breakdown(0.6), isAlternative: false },
    ],
  });

  it('accepts a grounded sentence', () => {
    const result = validateExplanations(
      { explanations: [{ taskId: 't1', memberId: 'm1', reason: 'Budi menguasai pengujian untuk tugas ini.' }] },
      ctx()
    );

    expect(result.failures).toEqual([]);
    expect(result.accepted.get('t1:m1')).toContain('Budi');
  });

  it('rejects an invented percentage', () => {
    const result = validateExplanations(
      { explanations: [{ taskId: 't1', memberId: 'm1', reason: 'Budi cocok 87% untuk tugas ini.' }] },
      ctx()
    );

    expect(result.accepted.size).toBe(0);
    expect(result.failures[0].reason).toMatch(/percentage|number/);
  });

  it('rejects a member who is not the subject', () => {
    const result = validateExplanations(
      { explanations: [{ taskId: 't1', memberId: 'm1', reason: 'Sari paling cocok untuk tugas ini.' }] },
      ctx()
    );

    expect(result.accepted.size).toBe(0);
    expect(result.failures[0].reason).toMatch(/not the subject/);
  });

  it('rejects a skill the task does not require', () => {
    const result = validateExplanations(
      {
        explanations: [
          {
            taskId: 't1',
            memberId: 'm1',
            reason: 'Budi memiliki keterampilan relevan (pemrograman frontend) untuk tugas ini.',
          },
        ],
      },
      ctx()
    );

    expect(result.accepted.size).toBe(0);
    expect(result.failures[0].reason).toMatch(/skill/);
  });

  it('rejects an unknown pairing', () => {
    const result = validateExplanations(
      { explanations: [{ taskId: 't9', memberId: 'm1', reason: 'Budi cocok.' }] },
      ctx()
    );

    expect(result.failures[0].reason).toMatch(/unexpected explanation target/);
  });

  it('rejects a malformed payload', () => {
    const result = validateExplanations({ nope: true }, ctx());

    expect(result.failures[0].reason).toMatch(/schema/);
  });

  describe('through the service', () => {
    it('uses one call for all explanations', async () => {
      const run = new AiRun('proj');
      const assigned = globalAssign(tasks, members, [], {
        cosineMap: { t1: { m1: 0.9, m2: 0.5 }, t2: { m1: 0.4, m2: 0.8 } },
        weights: DEFAULT_WEIGHTS,
      });
      spy.generateText = JSON.stringify({ explanations: [] });

      await explainAssignments({ tasks, members, result: assigned, isFallback: false, run });

      expect(spy.generateCalls).toBe(1);
    });

    it('makes zero calls in fallback mode and keeps templates', async () => {
      const run = new AiRun('proj');
      const assigned = globalAssign(tasks, members, [], { isFallback: true });

      const out = await explainAssignments({ tasks, members, result: assigned, isFallback: true, run });

      expect(spy.generateCalls).toBe(0);
      const reason = out.assignments[0].scores[out.assignments[0].primaryMemberId].reason;
      expect(reason).toContain('skor kesesuaian');
    });

    it('accepts valid model text and keeps templates elsewhere', async () => {
      const assigned = globalAssign(tasks, members, [], {
        cosineMap: { t1: { m1: 0.9, m2: 0.5 }, t2: { m1: 0.4, m2: 0.8 } },
        weights: DEFAULT_WEIGHTS,
      });
      const first = assigned.assignments[0];
      spy.generateText = JSON.stringify({
        explanations: [
          { taskId: first.taskId, memberId: first.primaryMemberId, reason: 'Nama dari model, dikuatkan data.' },
        ],
      });

      const out = await explainAssignments({ tasks, members, result: assigned, isFallback: false });
      const applied = out.assignments[0].scores[first.primaryMemberId].reason;

      // "Nama dari model" invents nothing, so it is accepted only if it names the member.
      // It does not, so the template must win.
      expect(applied).not.toBe('Nama dari model, dikuatkan data.');
      expect(applied).toContain('skor kesesuaian');
    });

    it('applies an accepted explanation that names its member', async () => {
      const assigned = globalAssign(tasks, members, [], {
        cosineMap: { t1: { m1: 0.9, m2: 0.5 }, t2: { m1: 0.4, m2: 0.8 } },
        weights: DEFAULT_WEIGHTS,
      });
      const first = assigned.assignments[0];
      const primaryName = members.find((m) => m.id === first.primaryMemberId)!.name;
      spy.generateText = JSON.stringify({
        explanations: [
          { taskId: first.taskId, memberId: first.primaryMemberId, reason: `${primaryName} siap mengerjakan tugas ini.` },
        ],
      });

      const out = await explainAssignments({ tasks, members, result: assigned, isFallback: false });

      expect(out.assignments[0].scores[first.primaryMemberId].reason).toBe(
        `${primaryName} siap mengerjakan tugas ini.`
      );
    });

    it('never changes scores or assignment when explanations fail', async () => {
      const assigned = globalAssign(tasks, members, [], {
        cosineMap: { t1: { m1: 0.9, m2: 0.5 }, t2: { m1: 0.4, m2: 0.8 } },
        weights: DEFAULT_WEIGHTS,
      });
      spy.generateText = 'not json at all';

      const out = await explainAssignments({ tasks, members, result: assigned, isFallback: false });

      expect(out.assignments.map((a) => a.primaryMemberId)).toEqual(
        assigned.assignments.map((a) => a.primaryMemberId)
      );
      expect(out.assignments[0].scores).toEqual(assigned.assignments[0].scores);
    });

    it('falls back to templates when the provider throws', async () => {
      const assigned = globalAssign(tasks, members, [], {
        cosineMap: { t1: { m1: 0.9, m2: 0.5 }, t2: { m1: 0.4, m2: 0.8 } },
        weights: DEFAULT_WEIGHTS,
      });
      spy.generateThrows = new Error('model unavailable');

      const out = await explainAssignments({ tasks, members, result: assigned, isFallback: false });
      const first = out.assignments[0];

      expect(first.scores[first.primaryMemberId].reason).toContain('skor kesesuaian');
    });

    it('skips the call entirely when the budget is already spent', async () => {
      const run = new AiRun('proj');
      const noop = async () => ({});
      await run.track('analysis', 'm', undefined, noop);
      await run.track('embedding', 'm', undefined, noop);
      await run.track('explanation', 'm', undefined, noop);

      const assigned = globalAssign(tasks, members, [], {
        cosineMap: { t1: { m1: 0.9, m2: 0.5 }, t2: { m1: 0.4, m2: 0.8 } },
        weights: DEFAULT_WEIGHTS,
      });
      const out = await explainAssignments({ tasks, members, result: assigned, isFallback: false, run });

      expect(spy.generateCalls).toBe(0);
      expect(out.assignments[0].scores[out.assignments[0].primaryMemberId].reason).toContain(
        'skor kesesuaian'
      );
    });
  });

  it('template reason stays deterministic for the same inputs', () => {
    const a = generateExplanation(tasks[0], members[0], breakdown(0.6));
    const b = generateExplanation(tasks[0], members[0], breakdown(0.6));

    expect(a).toBe(b);
  });
});

describe('FR-07/FR-13 regression under the new pipeline', () => {
  it('keeps the AI formula and the fallback weights intact', () => {
    const assigned = globalAssign(tasks, members, [], {
      cosineMap: { t1: { m1: 1, m2: 1 }, t2: { m1: 1, m2: 1 } },
      weights: DEFAULT_WEIGHTS,
    });
    const fbAssigned = globalAssign(tasks, members, [], { isFallback: true });

    const hybrid = assigned.assignments[0].scores[members[0].id].breakdown;
    expect(hybrid.total).toBeCloseTo(
      0.4 * hybrid.K + 0.3 * hybrid.S + 0.2 * hybrid.C + 0.1 * hybrid.M,
      10
    );

    const fb = fbAssigned.assignments[0].scores[members[0].id].breakdown;
    expect(fb.K).toBe(0);
    expect(fb.total).toBeCloseTo(
      FALLBACK_WEIGHTS.S * fb.S + FALLBACK_WEIGHTS.C * fb.C + FALLBACK_WEIGHTS.M * fb.M,
      10
    );
  });

  it('embeds everything in a single batched call through the guarded path', async () => {
    const run = new AiRun('proj');
    await computeTaskMemberCosineMap(tasks, members, run);

    expect(spy.embedCalls).toBe(1);
    expect(spy.embedBatchSizes).toEqual([tasks.length + members.length]);
  });
});

